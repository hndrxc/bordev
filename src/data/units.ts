export const UNITS = {
  crown: CROWN_UNITS,
  clans: CLANS_UNITS,
} as const;

export const ALL_UNITS: readonly UnitData[] = [
  ...Object.values(CROWN_UNITS),
  ...Object.values(CLANS_UNITS),
];

export function getUnitData(id: string, faction?: Faction): UnitData | undefined {
  if (faction) {
    const factionUnits = UNITS[faction];
    if (Object.hasOwn(factionUnits, id)) {
      return (factionUnits as Record<string, UnitData>)[id];
    }
    return undefined;
  }
  if (Object.hasOwn(CROWN_UNITS, id)) {
    return (CROWN_UNITS as Record<string, UnitData>)[id];
  }
  if (Object.hasOwn(CLANS_UNITS, id)) {
    return (CLANS_UNITS as Record<string, UnitData>)[id];
  }
  return undefined;
}
