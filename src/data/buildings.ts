export const BUILDINGS = {
  crown: CROWN_BUILDINGS,
  clans: CLANS_BUILDINGS,
} as const;

export const ALL_BUILDINGS: readonly BuildingData[] = [
  ...Object.values(CROWN_BUILDINGS),
  ...Object.values(CLANS_BUILDINGS),
];

export function getBuildingData(id: string, faction?: Faction): BuildingData | undefined {
  if (faction) {
    const factionBuildings = BUILDINGS[faction];
    if (Object.hasOwn(factionBuildings, id)) {
      return (factionBuildings as Record<string, BuildingData>)[id];
    }
    return undefined;
  }
  if (Object.hasOwn(CROWN_BUILDINGS, id)) {
    return (CROWN_BUILDINGS as Record<string, BuildingData>)[id];
  }
  if (Object.hasOwn(CLANS_BUILDINGS, id)) {
    return (CLANS_BUILDINGS as Record<string, BuildingData>)[id];
  }
  return undefined;
}
